/**
 * Writes docs/reviews/demo-chem-findings.md (step 4.3b, Phase 4 contract decisions Q11 addition 2): every CHEM finding on the demo's
 * species, reactions and mechanisms, for the human reviewer, and what could not be compared and why. Reads the demo, edits no data.
 * Run by hand: `node scripts/demo-chem-findings.mjs`. Nothing in it is marked verified.
 */
import { writeFileSync } from 'node:fs';
import { demoRecords } from './legacy-classify-kit';
import { stateOfRecords } from './legacy-map-kit';
import { realRig, sharedRdkit } from './l4-real-kit';
import type { AnyRecord, RecordKind } from '@/core/schema';

const OUT = 'docs/reviews/demo-chem-findings.md';
const KINDS: readonly ('species' | 'reaction' | 'mechanism')[] = ['species', 'reaction', 'mechanism'];

const state = stateOfRecords(demoRecords());
const rig = await realRig(state);
rig.service.checkAll();
await rig.service.flush();

const nameOf = (kind: RecordKind, id: string): string => {
  const record = (state.records[kind] as Readonly<Record<string, AnyRecord>>)[id] as unknown as { names?: { canonical?: string }; name?: string } | undefined;
  return record?.names?.canonical ?? record?.name ?? '(no name)';
};

const found = rig.findings.all({ level: 4 });
const perRule: Record<string, number> = {};
for (const finding of found) perRule[finding.ruleId] = (perRule[finding.ruleId] ?? 0) + 1;

const lines: string[] = [
  '# Demo chemistry findings (step 4.3b)',
  '',
  '**REVIEW REQUIRED.** Nothing here is marked verified; no demo data was edited. A finding says what the chem worker (RDKit) found when it',
  'checked the demo as written; whether the demo or the check is right is for the human reviewer to decide.',
  '',
  `Generated by \`node scripts/demo-chem-findings.mjs\` from \`data/seed/demo.orn.json\` with RDKit ${(await sharedRdkit()).version()}.`,
  `Checked: ${Object.keys(state.records.species).length} species (65 with a structure), ${Object.keys(state.records.reaction).length} reactions, ${Object.keys(state.records.mechanism).length} mechanisms; no class of the demo has a SMARTS.`,
  '',
  '## Findings per rule',
  '',
  ...['CHEM-001', 'CHEM-002', 'CHEM-003', 'CHEM-004', 'CHEM-005', 'CHEM-006', 'CHEM-007', 'CHEM-008', 'CHEM-009'].map(
    (id) => `- ${id}: ${perRule[id] ?? 0}`,
  ),
  '',
  '## Every finding',
  '',
  ...(found.length === 0
    ? ['None.']
    : found.map((f) => `- ${f.ruleId} (${f.severity}) on ${f.subject.kind} \`${f.subject.id}\` "${nameOf(f.subject.kind, f.subject.id)}"${f.path === undefined ? '' : `, path \`${f.path}\``}: ${f.message}`)),
  '',
  '## What could not be compared (said by the service, never silent)',
  '',
];
for (const kind of KINDS) {
  for (const id of Object.keys(state.records[kind]).sort()) {
    const status = rig.service.statusOf({ kind, id } as never);
    if (status.state === 'checked') for (const item of status.notCompared) lines.push(`- ${item.ruleId} on ${kind} \`${id}\` "${nameOf(kind, id)}": ${item.reason}`);
    else if (status.state === 'not_checked') lines.push(`- not checked: ${kind} \`${id}\`: ${status.reason}, ${status.message}`);
  }
}
lines.push(
  '',
  'CHEM-006 compares only the multisets of R/S and of E/Z letters of the stereo descriptors with the CIP labels RDKit gives (docs/VALIDATION_RULES.md, 2026-09-30 line); what it could not compare is listed above.',
  '',
  '## Questions for the reviewer',
  '',
  "- `spc_invalid-smiles-demo` is the demo's deliberately unparsable record (CHEM-001 is the expected finding). Confirm it stays in the demo.",
  '- `spc_palmitic-acid`: DATA CORRECTION BY THE REVIEWER (2026-09-30): the SMILES had 15 carbons; it is now `CCCCCCCCCCCCCCCC(=O)O` (16, hexadecanoic acid). The record stays REVIEW REQUIRED; nothing is marked verified, and CHEM-003 no longer fires for it.',
  '- Reactions: CHEM-005 compares nothing on the demo, because no reaction has a coefficient on every atom-contributing participant and a species (not a class or a reagent) for each of them. That is data, not a check failure.',
  '- Mechanisms: CHEM-008 is silent for all three. Mapped hydrogens (`[H:2]`) count as atoms of the step (RDKit removes them when it reads a structure; the adapter reads such a structure a second time to keep their maps).',
  '',
);
writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`wrote ${OUT}: ${found.length} findings`, perRule);
rig.service.dispose();
